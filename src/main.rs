/// asm explorer
#[derive(argh::FromArgs)]
struct Args {
    /// which snippet to render
    #[argh(option)]
    snippet: usize,

    /// json output
    #[argh(switch)]
    json: bool,
}

#[derive(Clone, Copy)]
pub enum IP {
    Abs(u32),
    SegOfs(u16, u16),
}

impl IP {
    pub fn bitness(&self) -> u32 {
        match self {
            IP::Abs(_) => 32,
            IP::SegOfs(_, _) => 16,
        }
    }

    pub fn eip(&self) -> u32 {
        match *self {
            IP::Abs(addr) => addr,
            IP::SegOfs(_, ofs) => ofs as u32,
        }
    }
}

fn main() {
    let args: Args = argh::from_env();
    let snippet = [&P1, &P2, &P3, &P4, &P5][args.snippet];
    let (instrs, blocks) = analyze(snippet);
    if args.json {
        json(&instrs, &blocks);
    } else {
        print(&instrs, &blocks);
    }
}

fn analyze(snippet: &Snippet) -> (Vec<iced_x86::Instruction>, Vec<Block>) {
    let decoder = Decoder::with_ip(
        snippet.ip.bitness(),
        snippet.code,
        snippet.ip.eip() as u64,
        DecoderOptions::NONE,
    );
    let instrs = decoder.into_iter().collect::<Vec<_>>();

    let stmts: Vec<Stmt> = instrs
        .iter()
        .map(|instr| Stmt {
            ip: vec![instr.ip32()],
            kind: StmtKind::from(instr),
        })
        .collect();
    let stmts = expand(stmts);
    let stmts = simp(stmts);
    let mut blocks = ssa::ssa(stmts);
    inline(&mut blocks);
    (instrs, blocks)
}

fn print(instrs: &[iced_x86::Instruction], blocks: &[Block]) {
    for instr in instrs {
        println!("{:08x} {}", instr.ip32(), instr);
    }

    for block in blocks.iter() {
        println!("{:x}:", block.ip);
        for stmt in &block.stmts {
            println!("  {}", stmt);
        }
        println!();
    }
}

fn json(instrs: &[iced_x86::Instruction], blocks: &[Block]) {
    #[derive(serde::Serialize)]
    struct JSON {
        instrs: Vec<(u32, String)>,
        blocks: Vec<(u32, Vec<(Vec<u32>, String)>)>,
    }

    let json = serde_json::to_string_pretty(&JSON {
        instrs: instrs
            .iter()
            .map(|instr| (instr.ip32(), format!("{instr}")))
            .collect(),
        blocks: blocks
            .iter()
            .map(|block| {
                let stmts = block
                    .stmts
                    .iter()
                    .map(|stmt| (stmt.ip.clone(), format!("{}", stmt.kind)))
                    .collect();
                (block.ip, stmts)
            })
            .collect(),
    })
    .unwrap();
    println!("{json}");
}

